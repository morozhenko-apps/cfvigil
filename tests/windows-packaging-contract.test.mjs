import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {fileURLToPath} from "node:url";
import path from "node:path";

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
const source=p=>readFileSync(path.join(root,p),"utf8");

test("Windows candidate is explicit, unsigned and uses a hosted runner",()=>{
  const workflow=source(".github/workflows/windows-candidate.yml");
  assert.match(workflow,/runs-on: windows-2025/);
  assert.match(workflow,/ci\/run-windows-candidate\.txt/);
  assert.match(workflow,/contents: read/);
  assert.doesNotMatch(workflow,/contents: write|gh release create|wrangler|R2_ACCESS_KEY|SIGNING_KEY/);
  // Windows ICO is source-controlled from the owner PNG and verified in CI.
  // Regenerating it in the runner introduces untracked, platform-dependent art.
  assert.match(workflow,/node scripts\/check-icon-assets\.mjs/);
  assert.match(workflow,/Check Windows Rust desktop with committed ICO and PNG/);
  assert.doesNotMatch(workflow,/cargo tauri icon/);
  assert.match(workflow,/cargo tauri build --bundles nsis --config tauri\.windows\.conf\.json/);
  assert.match(workflow,/cargo check --locked/);
  assert.match(workflow,/cargo test --locked/);
  assert.match(workflow,/node --test\s*\n/);
});

test("Windows overlay uses current-user installer, without mutating Linux config",()=>{
  const windows=JSON.parse(source("apps/desktop/src-tauri/tauri.windows.conf.json"));
  const base=JSON.parse(source("apps/desktop/src-tauri/tauri.conf.json"));
  assert.equal(windows.bundle.windows.nsis.installMode,"currentUser");
  assert.ok(windows.bundle.icon.includes("icons/icon.ico"));
  assert.equal(base.productName,"CFVigil");
  assert.ok(base.bundle.linux.deb.depends.includes("libgtk-layer-shell0"));
});

test("lockfile is source-controlled and reviewed by all CI gates",()=>{
  const lock=source("Cargo.lock");
  assert.match(lock,/^# This file is automatically @generated by Cargo\./);
  assert.match(lock,/^version = 4$/m);
  for(const file of [".github/workflows/checks.yml",
       ".github/workflows/package-candidate.yml",
       ".github/workflows/windows-candidate.yml"]) {
    assert.match(source(file),/cargo (check|metadata|test) --locked/);
  }
});

test("NSIS deletes only CFVigil's Windows credential on explicit full-data removal",()=>{
  const overlay=JSON.parse(source("apps/desktop/src-tauri/tauri.windows.conf.json"));
  const hooks=source("apps/desktop/src-tauri/windows/installer-hooks.nsh");
  const native=source("apps/desktop/src-tauri/src/main.rs");
  assert.equal(overlay.bundle.windows.nsis.installerHooks,"windows/installer-hooks.nsh");
  const service=native.match(/const KEYRING_SERVICE: &str = "([^"]+)"/)?.[1];
  const user=native.match(/const KEYRING_USER: &str = "([^"]+)"/)?.[1];
  assert.ok(service && user);
  assert.match(hooks,/!macro NSIS_HOOK_POSTUNINSTALL/);
  assert.match(hooks,/\$DeleteAppDataCheckboxState = 1/);
  assert.match(hooks,/\$UpdateMode <> 1/);
  assert.match(hooks,/CredDeleteW\(w "([^"]+)", i 1, i 0\) i \.r0/);
  const target=hooks.match(/CredDeleteW\(w "([^"]+)"/)?.[1];
  assert.equal(target,`${user}.${service}`,"must match keyring's Windows target");
  assert.match(hooks,/\$1 <> 1168/); // Already absent is an acceptable outcome
  assert.match(hooks,/MessageBox MB_ICONEXCLAMATION/); // Failures must be visible
  assert.doesNotMatch(hooks,/CredEnumerate|DeleteRegKey HKCU|RMDir \/r|cmdkey \/list/);
  assert.doesNotMatch(hooks,/NSIS_HOOK_PREINSTALL|NSIS_HOOK_POSTINSTALL/);
});
